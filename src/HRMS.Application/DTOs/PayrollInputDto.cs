public class SalaryAdjustmentDto
{
    public Guid Id { get; set; }
    public Guid EmployeeId { get; set; }
    public string EmployeeNo { get; set; } = string.Empty;
    public string EmployeeName { get; set; } = string.Empty;
    public string YearMonth { get; set; } = string.Empty;
    public string AdjustmentType { get; set; } = string.Empty;
    public decimal Amount { get; set; }
    public string SourceType { get; set; } = string.Empty;
    public string? SourceId { get; set; }
    public bool IsAutoGenerated { get; set; }
    public string? Remark { get; set; }
    public string? CreatedBy { get; set; }
    public DateTime CreatedAt { get; set; }
    public string? UpdatedBy { get; set; }
}

public class CreateSalaryAdjustmentDto
{
    [Required(ErrorMessage = "员工不能为空")]
    public Guid EmployeeId { get; set; }

    [Required(ErrorMessage = "年月不能为空")]
    [RegularExpression(@"^\d{4}-\d{2}$", ErrorMessage = "年月格式应为 YYYY-MM")]
    public string YearMonth { get; set; } = string.Empty;

    [Required(ErrorMessage = "调整项类型不能为空")]
    public string AdjustmentType { get; set; } = string.Empty;

    public decimal Amount { get; set; }
    public string SourceType { get; set; } = "Manual";
    public string? SourceId { get; set; }
    public bool IsAutoGenerated { get; set; }
    public string? Remark { get; set; }
    public string? CreatedBy { get; set; }
}

public class UpdateSalaryAdjustmentDto : CreateSalaryAdjustmentDto
{
    public Guid Id { get; set; }
    public string? UpdatedBy { get; set; }
}
