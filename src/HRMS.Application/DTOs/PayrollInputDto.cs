using System.ComponentModel.DataAnnotations;

namespace HRMS.Application.DTOs;

public class EmployeePayrollProfileDto
{
    public Guid Id { get; set; }
    public Guid EmployeeId { get; set; }
    public string EmployeeNo { get; set; } = string.Empty;
    public string EmployeeName { get; set; } = string.Empty;
    public Guid EmployeeTypeId { get; set; }
    public string EmployeeTypeName { get; set; } = string.Empty;
    public string? ShiftType { get; set; }
    public string? BankAccount { get; set; }
    public string PayrollStatus { get; set; } = string.Empty;
    public DateTime? JoinPayrollDate { get; set; }
    public DateTime? LeavePayrollDate { get; set; }
    public string? Remark { get; set; }
    public DateTime CreatedAt { get; set; }
}

public class CreateEmployeePayrollProfileDto
{
    [Required(ErrorMessage = "员工不能为空")]
    public Guid EmployeeId { get; set; }

    [Required(ErrorMessage = "员工类型不能为空")]
    public Guid EmployeeTypeId { get; set; }

    public string? ShiftType { get; set; }
    public string? BankAccount { get; set; }
    public string PayrollStatus { get; set; } = "Active";
    public DateTime? JoinPayrollDate { get; set; }
    public DateTime? LeavePayrollDate { get; set; }
    public string? Remark { get; set; }
}

public class UpdateEmployeePayrollProfileDto : CreateEmployeePayrollProfileDto
{
    public Guid Id { get; set; }
}

